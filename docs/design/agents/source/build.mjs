// Builds ../agents.html: one standalone preview of every artboard in this folder.
// Run from the repo root: node docs/design/agents/source/build.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const read = (name) => readFileSync(join(here, name), 'utf8');
const canvas = JSON.parse(read('canvas.json'));
const files = Object.fromEntries(
  readdirSync(here).filter((f) => f.endsWith('.dc.html')).map((f) => [f, read(f)])
);
const options = canvas.order
  .map((f) => `<option value="${f.replace('.dc.html', '')}">${canvas.boards[f].title}</option>`)
  .join('');
// Keep "</script>" inside the embedded files from closing the script tag.
const embedded = JSON.stringify(files).replace(/<\//g, '<\\/');

writeFileSync(
  join(here, '..', 'agents.html'),
  `<!doctype html>
<!-- Generated by source/build.mjs from the files in source/. Don't edit by hand. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Agents — approved CA-55 design</title>
<style>
body { margin: 0; background: #141517; }
#review { display: flex; flex-wrap: wrap; gap: 8px; align-items: center; padding: 10px 16px; font: 13px system-ui, sans-serif; color: #e8e9eb; background: #23252a; }
#review[hidden] { display: none; }
#review select { font: inherit; padding: 6px 8px; border-radius: 6px; border: 1px solid #3a3d43; background: #1f2023; color: inherit; }
${read('agents.css')}
</style>
<script>window.__DC_FILES = ${embedded};</script>
<script>${read('support.js')}</script>
</head>
<body>
<form id="review" aria-label="Review controls, not part of the design">
  <label>Screen <select name="screen">${options}</select></label>
  <label>Appearance <select name="theme"><option value="dark">Dark</option><option value="light">Light</option></select></label>
</form>
<div id="dc-root"></div>
<script>
  const params = new URLSearchParams(location.search);
  const review = document.getElementById('review');
  if (params.get('bare')) review.hidden = true;
  for (const s of review.querySelectorAll('select')) {
    if (params.get(s.name)) s.value = params.get(s.name);
    s.onchange = () => { params.set(s.name, s.value); location.search = params; };
  }
</script>
</body>
</html>
`
);
console.log('Wrote agents.html');
